#!/usr/bin/env python3
import sys
import os

def generate_vhdl_package(bin_file, vhdl_file):
    if not os.path.isfile(bin_file):
        print(f"Error: {bin_file} not found.")
        sys.exit(1)

    # Read the raw binary data
    with open(bin_file, "rb") as f:
        data = f.read()
        
    firmware_length = len(data)
    
    # VHDL arrays must have at least one element
    if firmware_length == 0:
        print("Error: Binary file is empty.")
        sys.exit(1)

    with open(vhdl_file, "w") as f:
        f.write("-- This file is auto-generated by the Makefile. DO NOT EDIT.\n")
        f.write("library ieee;\n")
        f.write("use ieee.std_logic_1164.all;\n\n")
        f.write("package firmware_pkg is\n\n")
        
        # Provide the exact length to your VHDL state machine
        f.write(f"    -- Exact size of the firmware binary in bytes\n")
        f.write(f"    constant FIRMWARE_LENGTH : integer := {firmware_length};\n\n")
        
        # Define the array type sized exactly to the firmware length
        f.write("    type rom_array is array (0 to FIRMWARE_LENGTH - 1) of std_logic_vector(7 downto 0);\n\n")
        
        f.write("    constant FIRMWARE_DATA : rom_array := (\n")
        
        # Write the bytes in chunks of 16 per line for editor readability
        for i in range(0, firmware_length, 16):
            chunk = data[i:i+16]
            hex_strings = [f'x"{b:02X}"' for b in chunk]
            line = "        " + ", ".join(hex_strings)
            
            # Add a comma unless it's the very last chunk
            if i + 16 < firmware_length:
                line += ","
            f.write(line + "\n")
            
        f.write("    );\n\n")
        f.write("end package firmware_pkg;\n")

if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python3 generate_rom.py <input.bin> <output_pkg.vhdl>")
        sys.exit(1)
        
    generate_vhdl_package(sys.argv[1], sys.argv[2])